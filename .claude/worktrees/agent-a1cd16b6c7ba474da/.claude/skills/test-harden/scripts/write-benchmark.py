#!/usr/bin/env python3
"""
write-benchmark.py — generate a benchmark report from a run result + state.

Usage:
  write-benchmark.py <phase> <scenario> <run-result-json> [findings-text]

Writes to platform/src/test/data/<phase>-*/benchmark-reports/YYYY-MM-DD-<scenario>.md
"""

import json
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

SKILL_ROOT = Path(__file__).parent.parent
REPO_ROOT = SKILL_ROOT.parent.parent.parent


def find_phase_data_dir(phase: str) -> Path:
    """Resolve platform/src/test/data/<phase-NN>-<name>/ — supports phase id prefix."""
    data_root = REPO_ROOT / "platform" / "src" / "test" / "data"
    candidates = [d for d in data_root.iterdir() if d.is_dir() and d.name.startswith(phase)]
    if not candidates:
        raise FileNotFoundError(f"no data dir starting with '{phase}' under {data_root}")
    return candidates[0]


def git_sha() -> str:
    try:
        p = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=REPO_ROOT)
        return p.stdout.strip()
    except Exception:
        return "unknown"


def render(phase: str, scenario: str, result: dict, state: dict, findings: str) -> str:
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    fixture_version = state.get("fixture_version", "v?")
    passed = result.get("passed", False)
    num_tests = result.get("num_tests", "?")
    num_passed = result.get("num_passed", "?")
    num_failed = result.get("num_failed", "?")
    duration = result.get("duration_ms", "?")
    complexity = state.get("complexity_score", 0)
    stressors = state.get("stressors_applied", [])

    # Metrics table — minimal at first; scenario-specific metrics filled in by orchestrator
    metrics_rows = [
        f"| Tests passed | {num_passed}/{num_tests} | pass all | {'✓' if num_failed == 0 else '✗'} |",
        f"| Duration | {duration}ms | scenario-specific | — |",
        f"| Complexity score | {complexity} | < 200 hard cap | {'✓' if complexity < 200 else '✗'} |",
    ]

    status_line = "All pass." if passed else "Failures detected — see findings."

    return f"""# {phase} {scenario} ({today})

## Setup

- **Data set version:** {fixture_version}
- **Fixture:** `{state.get('fixture_path', '?')}`
- **Expected:** `{state.get('expected_path', '?')}`
- **Test file:** `{state.get('test_file', '?')}`
- **Code commit:** `{git_sha()}`
- **Generated by:** `test-harden` skill

## Results

- **Status:** {status_line}
- **Tests:** {num_passed}/{num_tests} passed
- **Duration:** {duration}ms
- **Stressors applied:** {', '.join(stressors) if stressors else 'none (baseline)'}
- **Complexity:** {complexity}

## Metrics

| Metric | Value | Target | Pass |
|--------|-------|--------|------|
{chr(10).join(metrics_rows)}

## Findings

{findings or '_Pending orchestrator analysis._'}

## Next Iteration

- See scenario-state.json for consecutive-pass/fail counts
- Data Evolver proposals (if any) logged in `.claude/skills/test-harden/proposed-updates/`
- Code Analyser bead issues (if any) filed under the phase's beads tree

## Session

- Total runs for this scenario: {state.get('total_runs', 0)}
- Consecutive passes: {state.get('consecutive_passes', 0)}
- Consecutive fails: {state.get('consecutive_fails', 0)}
- Status: {state.get('status', 'active')}
"""


def main():
    if len(sys.argv) < 4:
        print(__doc__, file=sys.stderr)
        sys.exit(2)

    phase = sys.argv[1]
    scenario = sys.argv[2]
    result_path_or_json = sys.argv[3]
    findings = sys.argv[4] if len(sys.argv) > 4 else ""

    # Result can be path or inline JSON
    if Path(result_path_or_json).exists():
        with open(result_path_or_json) as f:
            result = json.load(f)
    else:
        result = json.loads(result_path_or_json)

    # Load state
    state_path = SKILL_ROOT / "scenario-state" / f"{phase}-{scenario}.json"
    if state_path.exists():
        with open(state_path) as f:
            state = json.load(f)
    else:
        state = {}

    # Resolve output path
    data_dir = find_phase_data_dir(phase)
    reports_dir = data_dir / "benchmark-reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    out_path = reports_dir / f"{today}-{scenario}.md"

    # If report for today already exists, append a suffix
    i = 1
    while out_path.exists():
        out_path = reports_dir / f"{today}-{scenario}-{i}.md"
        i += 1

    out_path.write_text(render(phase, scenario, result, state, findings), encoding="utf-8")
    print(str(out_path))


if __name__ == "__main__":
    main()
